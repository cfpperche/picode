// TestNotesAreOneLineOfStateNotAnEssay: chrome carries state and the next
// action. A note that explains how a store is built belongs in the
// architecture doc (.pi/skills/uiux-review, instant FAIL).
func TestNotesAreOneLineOfStateNotAnEssay(t *testing.T) {
	for _, cli := range Supported() {
		note := For(cli).note
		if note == "" {
			continue
		}
		if len(note) > 120 {
			t.Errorf("%s: note is %d characters, too long for chrome: %q", cli, len(note), note)
		}
		for _, word := range []string{"database", "SQLite", "sqlite", "git baseline", "index in a"} {
			if strings.Contains(note, word) {
				t.Errorf("%s: note explains the mechanism (%q), which belongs in the architecture doc: %q", cli, word, note)
			}
		}
	}
}
