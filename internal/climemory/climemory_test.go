// TestSecretShapesAreMaskedOnRead. The file keeps what the CLI wrote; the pane
// does not echo a credential back.
func TestSecretShapesAreMaskedOnRead(t *testing.T) {
	home, cwd := t.TempDir(), t.TempDir()
	dir := filepath.Join(home, ".claude", "projects", slugify(cwd), "memory")
	raw := "The deploy key is ghp_abcdefghijklmnopqrstuvwxyz012345 and the api key sk-ant-abcdefghijklmnopqrstuvwxyz.\nOrdinary prose about sk and about bearer tokens stays.\n"
	seed(t, filepath.Join(dir, "keys.md"), raw)
	body, err := Read("claude-code", Paths{Home: home, Cwd: cwd}, "workspace", "keys.md")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(body, "ghp_abcdefghijklmnopqrstuvwxyz012345") || strings.Contains(body, "sk-ant-abcdefghijklmnopqrstuvwxyz") {
		t.Fatalf("a credential was echoed: %q", body)
	}
	if !strings.Contains(body, "Ordinary prose about sk and about bearer tokens stays.") {
		t.Fatalf("prose was over-masked: %q", body)
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "keys.md")); string(got) != raw {
		t.Fatal("masking must not change the file")
	}
}

