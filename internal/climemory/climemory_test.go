func seed(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestTiersAreDeclaredNotInferred: the pane's capability comes from the
// catalog, so a CLI never gains an editor because a folder happened to exist.
func TestTiersAreDeclaredNotInferred(t *testing.T) {
	want := map[string]Tier{
		"claude-code": TierEditable,
		"hermes":      TierEditable,
		"muse":        TierEditable,
		"omp":         TierEditable,
		"grok":        TierReadOnly,
		"codex":       TierReadOnly,
		"pi":          TierNone,
		"opencode":    TierNone,
		"agy":         TierUnknown,
	}
	if len(Supported()) != len(want) {
		t.Fatalf("catalog has %d CLIs, the table has %d", len(Supported()), len(want))
	}
	for cli, tier := range want {
		rep, err := Describe(cli, Paths{Home: t.TempDir()})
		if err != nil {
			t.Fatalf("%s: %v", cli, err)
		}
		if rep.Tier != tier {
			t.Errorf("%s: tier %q, want %q", cli, rep.Tier, tier)
		}
		if tier == TierNone || tier == TierUnknown {
			if rep.Note == "" {
				t.Errorf("%s: a CLI with no memory owes the reader one line", cli)
			}
			if len(rep.Stores) != 0 {
				t.Errorf("%s: no memory means no stores, got %d", cli, len(rep.Stores))
			}
		}
	}
}

// TestReadOnlyTierRefusesWrites: Grok's and Codex's indexes are theirs.
func TestReadOnlyTierRefusesWrites(t *testing.T) {
	for _, cli := range []string{"grok", "codex"} {
		home := t.TempDir()
		var dir string
		switch cli {
		case "grok":
			dir = filepath.Join(home, ".grok", "memory-v2", "global")
		case "codex":
			dir = filepath.Join(home, ".codex", "memories")
		}
		seed(t, filepath.Join(dir, "MEMORY.md"), "# index\n\n> Generated by Grok. Do not edit this file directly.\n")
		seed(t, filepath.Join(dir, "testing.md"), "# testing\n\nUse make ci-scoped.\n")
		p := Paths{Home: home}
		if _, err := List(cli, p, "global"); err != nil {
			t.Fatalf("%s list: %v", cli, err)
		}
		if err := Write(cli, p, "global", "testing.md", "changed"); err == nil {
			t.Errorf("%s: a write must be refused", cli)
		}
		err := Delete(cli, p, "global", "testing.md")
		if err == nil {
			t.Errorf("%s: a delete must be refused", cli)
		} else if cli == "grok" && !strings.Contains(err.Error(), "grok memory clear") {
			t.Errorf("grok: the refusal should name the vendor command, got %q", err)
		}
		if _, err := os.Stat(filepath.Join(dir, "testing.md")); err != nil {
			t.Errorf("%s: the file must survive a refused delete", cli)
		}
	}
}

// TestEditableTierListsReadsWritesAndDeletes, on a Claude Code memory folder
// shaped like the real one.
func TestEditableTierListsReadsWritesAndDeletes(t *testing.T) {
	home, cwd := t.TempDir(), t.TempDir()
	dir := filepath.Join(home, ".claude", "projects", slugify(cwd), "memory")
	seed(t, filepath.Join(dir, "MEMORY.md"), "- [Role](user-role.md) — who the user is\n")
	seed(t, filepath.Join(dir, "user-role.md"), "---\nname: user-role\ndescription: The owner ships PiCode\nmetadata:\n  type: user\n---\n\nThe owner runs the repo.\n")
	p := Paths{Home: home, Cwd: cwd}

	items, err := List("claude-code", p, "workspace")
	if err != nil {
		t.Fatal(err)
	}
	if len(items) != 2 {
		t.Fatalf("want 2 items, got %d: %#v", len(items), items)
	}
	if !items[0].Index {
		t.Fatalf("the index sorts first, got %#v", items[0])
	}
	var fact Item
	for _, item := range items {
		if item.ID == "user-role.md" {
			fact = item
		}
	}
	if fact.Kind != "user" {
		t.Errorf("frontmatter type not read: %#v", fact)
	}
	if fact.Summary != "The owner ships PiCode" {
		t.Errorf("description not read: %q", fact.Summary)
	}

	body, err := Read("claude-code", p, "workspace", "user-role.md")
	if err != nil || !strings.Contains(body, "The owner runs the repo.") {
		t.Fatalf("read: %v %q", err, body)
	}
	if err := Write("claude-code", p, "workspace", "user-role.md", "changed\n"); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "user-role.md")); string(got) != "changed\n" {
		t.Fatalf("write did not land: %q", got)
	}
	if err := Delete("claude-code", p, "workspace", "user-role.md"); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "user-role.md")); !os.IsNotExist(err) {
		t.Fatal("delete did not remove the file")
	}
	// The index is not deletable: it is the map to everything else.
	if err := Delete("claude-code", p, "workspace", "MEMORY.md"); err == nil {
		t.Fatal("the index must not be deletable")
	}
}

