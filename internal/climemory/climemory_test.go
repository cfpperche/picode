// TestEveryToggleIsARealSettingsKey ties the two panes together: the switch the
// Memory pane offers must be a key the settings driver actually writes.
func TestEveryToggleIsARealSettingsKey(t *testing.T) {
	keys := map[string][]string{
		"claude-code": {"autoMemoryEnabled"},
		"codex":       {"features.memories", "memories.generate_memories", "memories.use_memories"},
		"hermes":      {"memory.memory_enabled", "memory.user_profile_enabled"},
		"omp":         {"memory.backend"},
	}
	for _, cli := range Supported() {
		s := For(cli)
		if s.toggle == "" {
			continue
		}
		declared, ok := keys[cli]
		if !ok {
			t.Errorf("%s declares a toggle %q with no settings keys listed here", cli, s.toggle)
			continue
		}
		found := false
		for _, key := range declared {
			if key == s.toggle {
				found = true
			}
		}
		if !found {
			t.Errorf("%s: toggle %q is not one of its settings keys %v", cli, s.toggle, declared)
		}
	}
}

