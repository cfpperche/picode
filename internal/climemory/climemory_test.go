// TestWorktreesShareTheRepositoryMemory: Claude Code keys its folder on the
// repository, so a PiCode worktree must read the same memory as its main
// checkout instead of an empty one.
func TestWorktreesShareTheRepositoryMemory(t *testing.T) {
	home := t.TempDir()
	repo := filepath.Join(t.TempDir(), "project")
	tree := filepath.Join(repo, ".worktrees", "feature")
	if err := os.MkdirAll(filepath.Join(repo, ".git", "worktrees", "feature"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(tree, 0o755); err != nil {
		t.Fatal(err)
	}
	seed(t, filepath.Join(tree, ".git"), "gitdir: "+filepath.Join(repo, ".git", "worktrees", "feature")+"\n")
	dir := filepath.Join(home, ".claude", "projects", slugify(repo), "memory")
	seed(t, filepath.Join(dir, "MEMORY.md"), "- one line\n")

	rep, err := Describe("claude-code", Paths{Home: home, Cwd: tree})
	if err != nil {
		t.Fatal(err)
	}
	if !rep.Stores[0].Exists || rep.Stores[0].Path != dir {
		t.Fatalf("a worktree must resolve to the repository's memory, got %#v", rep.Stores[0])
	}
}

// TestGrokWorkspaceIsMatchedOrRefused: Grok hashes the workspace path into the
// folder name. PiCode matches on the name and says unknown when the match is
// ambiguous rather than showing another project's memory.
func TestGrokWorkspaceIsMatchedOrRefused(t *testing.T) {
	home := t.TempDir()
	base := filepath.Join(home, ".grok", "memory-v2", "workspaces")
	cwd := filepath.Join(t.TempDir(), "picode")
	if err := os.MkdirAll(cwd, 0o755); err != nil {
		t.Fatal(err)
	}
	seed(t, filepath.Join(base, "picode-e1f77c5c", "MEMORY.md"), "# index\n")
	seed(t, filepath.Join(base, "other-1234abcd", "MEMORY.md"), "# index\n")
	rep, err := Describe("grok", Paths{Home: home, Cwd: cwd})
	if err != nil {
		t.Fatal(err)
	}
	ws := rep.Stores[1]
	if !ws.Resolved || !strings.HasSuffix(ws.Path, "picode-e1f77c5c") {
		t.Fatalf("want the matching folder, got %#v", ws)
	}

	// A second folder with the same workspace name is ambiguous.
	seed(t, filepath.Join(base, "picode-99999999", "MEMORY.md"), "# index\n")
	rep, _ = Describe("grok", Paths{Home: home, Cwd: cwd})
	ws = rep.Stores[1]
	if ws.Resolved || ws.Note == "" {
		t.Fatalf("an ambiguous match must be reported, got %#v", ws)
	}
	if _, err := List("grok", Paths{Home: home, Cwd: cwd}, "workspace"); err == nil {
		t.Fatal("listing an unresolved store must refuse")
	}
}

