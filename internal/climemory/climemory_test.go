// gitRepo makes `dir` a repository of its own and commits whatever is in it.
// The identity and the empty hooks path keep the commit independent of the
// machine's git configuration.
func gitRepo(t *testing.T, dir, subject string) {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not installed")
	}
	run := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-C", dir,
			"-c", "user.name=Codex", "-c", "user.email=codex@example.test",
			"-c", "commit.gpgsign=false", "-c", "core.hooksPath="}, args...)...)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, ".git")); err != nil {
		run("init", "-q", "-b", "main")
	}
	run("add", "-A", ".")
	run("commit", "-q", "-m", subject)
}

// TestHistoryReadsTheStoresOwnRepository: Codex keeps `~/.codex/memories`
// under git, and the revision that last touched a file is a truer answer than
// the mtime — the CLI rewrites those files with the same bytes.
func TestHistoryReadsTheStoresOwnRepository(t *testing.T) {
	home := t.TempDir()
	dir := filepath.Join(home, ".codex", "memories")
	seed(t, filepath.Join(dir, "MEMORY.md"), "# index\n\n> Generated by Codex. Do not edit this file directly.\n")
	seed(t, filepath.Join(dir, "raw_memories.md"), "Merged stage-1 raw memories.\n")
	gitRepo(t, dir, "Initialize Codex git baseline")
	// mtime moves without the content changing: exactly the case the revision
	// date exists to answer.
	future := time.Now().Add(2 * time.Hour)
	if err := os.Chtimes(filepath.Join(dir, "raw_memories.md"), future, future); err != nil {
		t.Fatal(err)
	}

	items, audit, err := Survey("codex", Paths{Home: home}, "global")
	if err != nil {
		t.Fatal(err)
	}
	if audit.History == nil {
		t.Fatal("a store that is a git repository reports its history")
	}
	if audit.History.Revisions != 1 || audit.History.Subject != "Initialize Codex git baseline" {
		t.Errorf("one baseline revision: %#v", audit.History)
	}
	if len(audit.History.Changed) != 0 {
		t.Errorf("a clean tree has changed nothing: %v", audit.History.Changed)
	}
	for _, item := range items {
		if item.ModifiedFrom != "git" {
			t.Errorf("%s should date from its revision, not the filesystem: %q", item.ID, item.ModifiedFrom)
		}
	}

	// A file the CLI has rewritten since the last revision is newer than any
	// revision, so the filesystem is the honest answer again.
	seed(t, filepath.Join(dir, "raw_memories.md"), "Merged stage-1 raw memories, and one more.\n")
	items, audit, err = Survey("codex", Paths{Home: home}, "global")
	if err != nil {
		t.Fatal(err)
	}
	if len(audit.History.Changed) != 1 || audit.History.Changed[0] != "raw_memories.md" {
		t.Errorf("the rewritten file is named: %v", audit.History.Changed)
	}
	for _, item := range items {
		want := "git"
		if item.ID == "raw_memories.md" {
			want = "file"
		}
		if item.ModifiedFrom != want {
			t.Errorf("%s: want %q, got %q", item.ID, want, item.ModifiedFrom)
		}
	}
}

// TestHistoryIsTheStoresOwnOrNothing: a memory folder inside the user's
// repository must not report that project's history as the memory's, and a CLI
// whose own timestamp is in the file keeps it.
func TestHistoryIsTheStoresOwnOrNothing(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not installed")
	}
	t.Run("a store with no repository of its own", func(t *testing.T) {
		home, cwd := t.TempDir(), t.TempDir()
		// The workspace is a repository; the memory folder inside it is not.
		seed(t, filepath.Join(cwd, "README.md"), "project\n")
		gitRepo(t, cwd, "the user's own project")
		dir := filepath.Join(cwd, ".agents", "memory")
		seed(t, filepath.Join(dir, "notes.md"), "Muse keeps memory in the workspace.\n")
		_, audit, err := Survey("muse", Paths{Home: home, Cwd: cwd}, "workspace")
		if err != nil {
			t.Fatal(err)
		}
		if audit.History != nil {
			t.Errorf("the project's history is not the memory's: %#v", audit.History)
		}
	})
	t.Run("a changed file whose name has a space", func(t *testing.T) {
		// git quotes and backslash-escapes such a path in the plain porcelain
		// format; a name parsed wrong would leave the file wearing a revision
		// date it no longer matches.
		home := t.TempDir()
		dir := filepath.Join(home, ".codex", "memories")
		seed(t, filepath.Join(dir, "raw memories.md"), "one\n")
		gitRepo(t, dir, "baseline")
		seed(t, filepath.Join(dir, "raw memories.md"), "one, and two\n")
		items, audit, err := Survey("codex", Paths{Home: home}, "global")
		if err != nil {
			t.Fatal(err)
		}
		if len(audit.History.Changed) != 1 || audit.History.Changed[0] != "raw memories.md" {
			t.Fatalf("the rewritten file is named whole: %q", audit.History.Changed)
		}
		for _, item := range items {
			if item.ID == "raw memories.md" && item.ModifiedFrom != "file" {
				t.Errorf("a file with uncommitted changes keeps the filesystem's date: %q", item.ModifiedFrom)
			}
		}
	})
	t.Run("the memory's own timestamp still wins", func(t *testing.T) {
		home := t.TempDir()
		dir := filepath.Join(home, ".codex", "memories")
		seed(t, filepath.Join(dir, "MEMORY.md"), "---\nname: index\nmetadata:\n  modified: 2026-01-02T03:04:05.000Z\n---\n\nindex\n")
		gitRepo(t, dir, "baseline")
		items, _, err := Survey("codex", Paths{Home: home}, "global")
		if err != nil {
			t.Fatal(err)
		}
		for _, item := range items {
			if item.ID == "MEMORY.md" && (item.ModifiedFrom != "memory" || item.Modified != "2026-01-02T03:04:05.000Z") {
				t.Errorf("the CLI's own date outranks the revision: %q %q", item.Modified, item.ModifiedFrom)
			}
		}
	})
}
